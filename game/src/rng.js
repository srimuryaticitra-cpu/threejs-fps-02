// Seeded RNG for KURA OPS: every round draws from one mulberry32 stream, so a
// ?shot=...&seed=N capture and a fresh round with the same seed play the same.
// The stream is the only source of randomness in the simulation; rendering never
// draws from it, which keeps replays deterministic.
export function mulberry32(initialSeed) {
  let a = initialSeed | 0;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function range(random, min, max) {
  return min + random() * (max - min);
}

export function pick(random, list) {
  return list[Math.floor(random() * list.length)];
}

export function clamp(value, min, max) {
  return value < min ? min : value > max ? max : value;
}

export function lerp(a, b, t) {
  return a + (b - a) * t;
}
